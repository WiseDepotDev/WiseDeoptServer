<#
.SYNOPSIS
    错误码生成器：把《后端异常码对照表.csv》生成三端错误码产物。

.DESCRIPTION
    单一来源（STD-CONTRACT-03）：
      - 值（code / message / httpStatus）唯一来源 = WiseDeoptServer/wise-depot-plan/后端异常码对照表.csv
      - 名称 / 顺序 / 分组唯一来源 = tools/gen/errorcode-manifest.json
        （manifest 中 origin=supplement 的条目为对照表尚未登记的扩展码，其值随 manifest 维护）

    产物（全部带 AUTO-GENERATED 头，禁止手改）：
      - 服务端 WiseDeoptServer/.../common/api/ErrorCode.java
      - APP   WiseDepotApp/.../network/ErrorCode.kt
      - 设备端 WiseDepotDevice/include/common/error_code.h
      - 设备端 WiseDepotDevice/src/common/error_code.c

.PARAMETER Check
    只校验不写入：逐文件报告「一致 / 有差异」，任一文件有差异则以退出码 1 结束（用于 CI 门禁）。

.PARAMETER Root
    工作区根目录。默认取脚本所在目录的上两级。

.EXAMPLE
    pwsh tools/gen/gen-errorcodes.ps1 -Check
    pwsh tools/gen/gen-errorcodes.ps1
#>
[CmdletBinding()]
param(
    [switch]$Check,
    [string]$Root
)

$ErrorActionPreference = 'Stop'
if (-not $Root) {
    # 从脚本所在目录向上查找工作区根（同时包含 APP 与设备端目录的那一层）
    $probe = $PSScriptRoot
    while ($probe) {
        if ((Test-Path (Join-Path $probe 'WiseDepotDevice')) -and (Test-Path (Join-Path $probe 'WiseDepotApp'))) { break }
        $parent = Split-Path $probe -Parent
        if (-not $parent -or $parent -eq $probe) { $probe = $null; break }
        $probe = $parent
    }
    if (-not $probe) { throw '无法定位工作区根目录（应包含 WiseDepotApp 与 WiseDepotDevice），请用 -Root 显式指定。' }
    $Root = $probe
}
$manifestPath = Join-Path $PSScriptRoot 'errorcode-manifest.json'
$utf8 = New-Object System.Text.UTF8Encoding($false)

function Write-File($path, $content) {
    $dir = Split-Path $path
    if (-not (Test-Path $dir)) { New-Item -ItemType Directory $dir -Force | Out-Null }
    [System.IO.File]::WriteAllText($path, (Normalize-Lf $content), $utf8)
}

# 统一换行为 LF，保证跨平台生成结果一致（STD-CODE-04）
function Normalize-Lf($s) {
    return ($s -replace "`r`n", "`n") -replace "`r", "`n"
}

function Escape-Json($s) {
    return ($s -replace '\\', '\\\\') -replace '"', '\"'
}

# ---------- 1. 读取清单与 CSV ----------
if (-not (Test-Path $manifestPath)) { throw "缺少清单文件：$manifestPath" }
$manifest = Get-Content $manifestPath -Raw -Encoding UTF8 | ConvertFrom-Json
$csvPath = Join-Path $Root $manifest.csvSource
if (-not (Test-Path $csvPath)) { throw "缺少错误码对照表：$csvPath" }

$csvValues = @{}
Import-Csv $csvPath | Where-Object { $_ -and $_.'异常码（ErrorCode）' -and $_.'异常码（ErrorCode）' -ne '--' } | ForEach-Object {
    $csvValues[$_.'异常码（ErrorCode）'] = @{
        message    = $_.'异常描述'
        httpStatus = [int]$_.'HTTP状态码'
    }
}
Write-Host ("[gen] 对照表条目: {0}" -f $csvValues.Count)

# ---------- 2. 解析每条错误码的最终值 ----------
$resolved = @()
foreach ($e in $manifest.entries) {
    if ($e.origin -eq 'csv') {
        if (-not $csvValues.ContainsKey($e.code)) {
            throw ("错误码 {0}（{1}）标注为 csv 来源，但对照表中不存在。请先在对照表登记，或把 manifest 中该条改为 origin=supplement。" -f $e.code, $e.name)
        }
        $v = $csvValues[$e.code]
        $resolved += [pscustomobject]@{ group = $e.group; name = $e.name; code = $e.code; message = $v.message; httpStatus = $v.httpStatus; origin = 'csv' }
    }
    else {
        $resolved += [pscustomobject]@{ group = $e.group; name = $e.name; code = $e.code; message = $e.message; httpStatus = [int]$e.httpStatus; origin = 'supplement' }
    }
}
Write-Host ("[gen] 清单条目: {0}（csv={1} supplement={2}）" -f $resolved.Count,
    ($resolved | Where-Object { $_.origin -eq 'csv' }).Count,
    ($resolved | Where-Object { $_.origin -eq 'supplement' }).Count)

$dupName = $resolved | Group-Object name | Where-Object { $_.Count -gt 1 }
if ($dupName) { throw ("清单中存在重复常量名：" + (($dupName | ForEach-Object { $_.Name }) -join ', ')) }
$dupCode = $resolved | Group-Object code | Where-Object { $_.Count -gt 1 }
if ($dupCode) { throw ("清单中存在重复错误码：" + (($dupCode | ForEach-Object { $_.Name }) -join ', ')) }

# ---------- 3. 渲染常量块（Java / Kotlin 语法一致）----------
$sb = New-Object System.Text.StringBuilder
$groups = $resolved | Group-Object group | Sort-Object { [int]$_.Name }
$groupIndex = 0
$totalGroups = $groups.Count
foreach ($g in $groups) {
    if ($groupIndex -gt 0) { [void]$sb.AppendLine() }
    $groupIndex++
    $items = $g.Group
    for ($i = 0; $i -lt $items.Count; $i++) {
        $it = $items[$i]
        $isVeryLast = ($groupIndex -eq $totalGroups) -and ($i -eq $items.Count - 1)
        $tail = if ($isVeryLast) { ');' } else { '),' }
        [void]$sb.AppendLine(('    {0}("{1}", "{2}", {3}{4}' -f $it.name, $it.code, (Escape-Json $it.message), $it.httpStatus, $tail))
    }
}
# 去掉末尾多余换行，模板尾自带换行
$constants = $sb.ToString().TrimEnd("`r", "`n")

# ---------- 4. 渲染设备端 C 头/.c ----------
$cHeaderSb = New-Object System.Text.StringBuilder
[void]$cHeaderSb.AppendLine('/**')
[void]$cHeaderSb.AppendLine(' * @file error_code.h')
[void]$cHeaderSb.AppendLine(' * @brief 慧仓智控设备端错误码定义（AUTO-GENERATED BY tools/gen/gen-errorcodes.ps1 — DO NOT EDIT）')
[void]$cHeaderSb.AppendLine(' *')
[void]$cHeaderSb.AppendLine(' * 唯一来源：WiseDeoptServer/wise-depot-plan/后端异常码对照表.csv')
[void]$cHeaderSb.AppendLine(' * 名称与顺序来源：tools/gen/errorcode-manifest.json')
[void]$cHeaderSb.AppendLine(' */')
[void]$cHeaderSb.AppendLine('#ifndef WISE_DEPOT_COMMON_ERROR_CODE_H')
[void]$cHeaderSb.AppendLine('#define WISE_DEPOT_COMMON_ERROR_CODE_H')
[void]$cHeaderSb.AppendLine()
[void]$cHeaderSb.AppendLine('#ifdef __cplusplus')
[void]$cHeaderSb.AppendLine('extern "C" {')
[void]$cHeaderSb.AppendLine('#endif')
[void]$cHeaderSb.AppendLine()
[void]$cHeaderSb.AppendLine('/** 错误码信息表项：错误码、中文描述、HTTP 语义状态码 */')
[void]$cHeaderSb.AppendLine('typedef struct {')
[void]$cHeaderSb.AppendLine('    const char *code;        /**< 错误码，如 "AUTH-REQUEST-1001" */')
[void]$cHeaderSb.AppendLine('    const char *message;     /**< 中文描述 */')
[void]$cHeaderSb.AppendLine('    int         http_status; /**< 对应的 HTTP 状态码 */')
[void]$cHeaderSb.AppendLine('} wd_error_info_t;')
[void]$cHeaderSb.AppendLine()
[void]$cHeaderSb.AppendLine('/* ===== 错误码宏定义（与三端保持一致）===== */')
foreach ($it in $resolved) {
    [void]$cHeaderSb.AppendLine(('#define WD_{0,-38} "{1}"' -f $it.name, $it.code))
}
[void]$cHeaderSb.AppendLine()
[void]$cHeaderSb.AppendLine('/**')
[void]$cHeaderSb.AppendLine(' * @brief 按错误码查表取信息。')
[void]$cHeaderSb.AppendLine(' * @param code 错误码字符串，可为 NULL')
[void]$cHeaderSb.AppendLine(' * @return 匹配到的表项；未匹配时返回 NULL')
[void]$cHeaderSb.AppendLine(' */')
[void]$cHeaderSb.AppendLine('const wd_error_info_t *wd_error_lookup(const char *code);')
[void]$cHeaderSb.AppendLine()
[void]$cHeaderSb.AppendLine('/**')
[void]$cHeaderSb.AppendLine(' * @brief 取错误码的中文描述。')
[void]$cHeaderSb.AppendLine(' * @param code 错误码字符串，可为 NULL')
[void]$cHeaderSb.AppendLine(' * @return 描述字符串；未匹配时返回 "未知错误"')
[void]$cHeaderSb.AppendLine(' */')
[void]$cHeaderSb.AppendLine('const char *wd_error_message(const char *code);')
[void]$cHeaderSb.AppendLine()
[void]$cHeaderSb.AppendLine('/**')
[void]$cHeaderSb.AppendLine(' * @brief 判断错误码是否表示成功。')
[void]$cHeaderSb.AppendLine(' * @param code 错误码字符串，可为 NULL')
[void]$cHeaderSb.AppendLine(' * @return 1 表示成功，0 表示失败')
[void]$cHeaderSb.AppendLine(' */')
[void]$cHeaderSb.AppendLine('int wd_error_is_success(const char *code);')
[void]$cHeaderSb.AppendLine()
[void]$cHeaderSb.AppendLine('/* 成功错误码，单独提供便于比较 */')
[void]$cHeaderSb.AppendLine(('#define WD_ERROR_SUCCESS "{0}"' -f $resolved[0].code))
[void]$cHeaderSb.AppendLine()
[void]$cHeaderSb.AppendLine('#ifdef __cplusplus')
[void]$cHeaderSb.AppendLine('}')
[void]$cHeaderSb.AppendLine('#endif')
[void]$cHeaderSb.AppendLine()
[void]$cHeaderSb.AppendLine('#endif /* WISE_DEPOT_COMMON_ERROR_CODE_H */')

$cSourceSb = New-Object System.Text.StringBuilder
[void]$cSourceSb.AppendLine('/**')
[void]$cSourceSb.AppendLine(' * @file error_code.c')
[void]$cSourceSb.AppendLine(' * @brief 设备端错误码查表实现（AUTO-GENERATED BY tools/gen/gen-errorcodes.ps1 — DO NOT EDIT）')
[void]$cSourceSb.AppendLine(' */')
[void]$cSourceSb.AppendLine('#include <string.h>')
[void]$cSourceSb.AppendLine()
[void]$cSourceSb.AppendLine('#include "common/error_code.h"')
[void]$cSourceSb.AppendLine()
[void]$cSourceSb.AppendLine('/** 错误码表，顺序与 tools/gen/errorcode-manifest.json 一致 */')
[void]$cSourceSb.AppendLine('static const wd_error_info_t WD_ERROR_TABLE[] = {')
foreach ($it in $resolved) {
    [void]$cSourceSb.AppendLine(('    {{ {0,-38}, "{1}", {2} }},' -f ("WD_" + $it.name), (Escape-Json $it.message), $it.httpStatus))
}
[void]$cSourceSb.AppendLine('};')
[void]$cSourceSb.AppendLine()
[void]$cSourceSb.AppendLine('const wd_error_info_t *wd_error_lookup(const char *code) {')
[void]$cSourceSb.AppendLine('    size_t i;')
[void]$cSourceSb.AppendLine()
[void]$cSourceSb.AppendLine('    if (code == NULL) {')
[void]$cSourceSb.AppendLine('        return NULL;')
[void]$cSourceSb.AppendLine('    }')
[void]$cSourceSb.AppendLine()
[void]$cSourceSb.AppendLine('    for (i = 0; i < sizeof(WD_ERROR_TABLE) / sizeof(WD_ERROR_TABLE[0]); i++) {')
[void]$cSourceSb.AppendLine('        if (strcmp(WD_ERROR_TABLE[i].code, code) == 0) {')
[void]$cSourceSb.AppendLine('            return &WD_ERROR_TABLE[i];')
[void]$cSourceSb.AppendLine('        }')
[void]$cSourceSb.AppendLine('    }')
[void]$cSourceSb.AppendLine()
[void]$cSourceSb.AppendLine('    return NULL;')
[void]$cSourceSb.AppendLine('}')
[void]$cSourceSb.AppendLine()
[void]$cSourceSb.AppendLine('const char *wd_error_message(const char *code) {')
[void]$cSourceSb.AppendLine('    const wd_error_info_t *info = wd_error_lookup(code);')
[void]$cSourceSb.AppendLine()
[void]$cSourceSb.AppendLine('    return (info != NULL) ? info->message : "未知错误";')
[void]$cSourceSb.AppendLine('}')
[void]$cSourceSb.AppendLine()
[void]$cSourceSb.AppendLine('int wd_error_is_success(const char *code) {')
[void]$cSourceSb.AppendLine('    if (code == NULL) {')
[void]$cSourceSb.AppendLine('        return 0;')
[void]$cSourceSb.AppendLine('    }')
[void]$cSourceSb.AppendLine()
[void]$cSourceSb.AppendLine('    return (strcmp(code, WD_ERROR_SUCCESS) == 0) ? 1 : 0;')
[void]$cSourceSb.AppendLine('}')

# ---------- 5. 组装产物 ----------
$products = @()

$javaTplPath = Join-Path $PSScriptRoot 'templates\ErrorCode.java.tpl'
$ktTplPath = Join-Path $PSScriptRoot 'templates\ErrorCode.kt.tpl'
foreach ($tpl in @($javaTplPath, $ktTplPath)) {
    if (-not (Test-Path $tpl)) { throw "缺少模板文件：$tpl" }
}

$products += [pscustomobject]@{
    path    = Join-Path $Root $manifest.outputs.java
    content = ([System.IO.File]::ReadAllText($javaTplPath)).Replace('@@CONSTANTS@@', $constants)
}
$products += [pscustomobject]@{
    path    = Join-Path $Root $manifest.outputs.kotlin
    content = ([System.IO.File]::ReadAllText($ktTplPath)).Replace('@@CONSTANTS@@', $constants)
}
$products += [pscustomobject]@{
    path    = Join-Path $Root $manifest.outputs.cHeader
    content = $cHeaderSb.ToString()
}
$products += [pscustomobject]@{
    path    = Join-Path $Root ($manifest.outputs.cHeader -replace 'include/common/error_code\.h$', 'src/common/error_code.c')
    content = $cSourceSb.ToString()
}

# ---------- 6. 写入或校验 ----------
$diffCount = 0
foreach ($p in $products) {
    $rel = $p.path.Substring($Root.Length + 1)
    $existing = if (Test-Path $p.path) { [System.IO.File]::ReadAllText($p.path) } else { $null }
    $expected = Normalize-Lf $p.content
    if ($null -ne $existing -and (Normalize-Lf $existing) -eq $expected) {
        Write-Host ("[gen] 一致    {0}" -f $rel)
        continue
    }
    if ($Check) {
        $state = if ($null -eq $existing) { '缺失' } else { '有差异' }
        Write-Host ("[gen] {0}  {1}" -f $state, $rel) -ForegroundColor Yellow
        $diffCount++
    }
    else {
        Write-File $p.path $p.content
        $state = if ($null -eq $existing) { '已创建' } else { '已更新' }
        Write-Host ("[gen] {0}  {1}" -f $state, $rel)
    }
}

if ($Check) {
    if ($diffCount -gt 0) {
        Write-Host ("[gen] 校验失败：{0} 个产物与对照表不一致，请运行 pwsh tools/gen/gen-errorcodes.ps1 重新生成。" -f $diffCount) -ForegroundColor Red
        exit 1
    }
    Write-Host '[gen] 校验通过：三端错误码产物与对照表一致。' -ForegroundColor Green
    exit 0
}

Write-Host ("[gen] 完成：共 {0} 个产物（错误码 {1} 条）。" -f $products.Count, $resolved.Count) -ForegroundColor Green
